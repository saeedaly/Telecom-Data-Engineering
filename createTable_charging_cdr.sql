CREATE TABLE IF NOT EXISTS CHARGING_CDRs (
    LOCAL_TIME TIMESTAMP NOT NULL,
    SERVICE_CLASS_ID VARCHAR(20),
    SERVIED_MSISDN VARCHAR(20) NOT NULL PRIMARY KEY,
    SERVICE_IDENTIFIER_ID VARCHAR(3),
    CALLED_NUMBER VARCHAR(20),
    CALLING_NUMBER VARCHAR(20),
    DURATION VARCHAR(20),
    VOLUME VARCHAR(20));